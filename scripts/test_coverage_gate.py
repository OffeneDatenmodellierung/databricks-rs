import json
import os
import tempfile
import unittest
from contextlib import redirect_stdout
from io import StringIO

import coverage_gate


def report(path):
    return {"files": [{"path": path, "covered": 9, "coverable": 10, "content": ""}]}


class PathShapes(unittest.TestCase):
    def run_gate(self, path):
        with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
            json.dump(report(path), f)
        out = StringIO()
        try:
            with redirect_stdout(out):
                rc = coverage_gate.main(f.name)
        finally:
            os.unlink(f.name)
        return rc, out.getvalue()

    def test_component_list(self):
        rc, out = self.run_gate(["/", "w", "crates", "c", "src", "lib.rs"])
        self.assertEqual(rc, 0)
        self.assertIn("crates/c/src/lib.rs", out)

    def test_string_path(self):
        rc, out = self.run_gate("/w/crates/c/src/lib.rs")
        self.assertEqual(rc, 0)
        self.assertIn("crates/c/src/lib.rs", out)


class GeneratedFiles(unittest.TestCase):
    def test_generated_files_are_exempt_with_or_without_content(self):
        with tempfile.TemporaryDirectory() as d:
            gen = os.path.join(d, "crates", "g", "src")
            os.makedirs(gen)
            lib = os.path.join(gen, "lib.rs")
            with open(lib, "w") as f:
                f.write("// Code generated by `cargo xtask codegen`. DO NOT EDIT.\n")
            parts = ["/"] + [p for p in lib.split(os.sep) if p]
            low = {"covered": 1, "coverable": 10}
            # A second generated file, reported as an absolute string path.
            gen2 = os.path.join(d, "crates", "s", "src")
            os.makedirs(gen2)
            lib2 = os.path.join(gen2, "lib.rs")
            with open(lib2, "w") as f:
                f.write("// Code generated by `cargo xtask codegen`. DO NOT EDIT.\n")
            report = {"files": [
                dict(low, path=parts),  # no `content`: read from disk
                dict(low, path=lib2),  # string path, no `content`
                dict(low, path="/w/crates/h/src/lib.rs", content="// Code generated x\n"),
                dict(low, path="/w/crates/x/src/lib.rs", content="fn main() {}\n"),
            ]}
            rpt = os.path.join(d, "r.json")
            with open(rpt, "w") as f:
                json.dump(report, f)
            out = StringIO()
            with redirect_stdout(out):
                rc = coverage_gate.main(rpt)
        self.assertEqual(rc, 1)
        self.assertIn("crates/x/src/lib.rs  FAIL", out.getvalue())
        self.assertNotIn("crates/g/src/lib.rs", out.getvalue())
        self.assertNotIn("crates/s/src/lib.rs", out.getvalue())
        self.assertNotIn("crates/h/src/lib.rs", out.getvalue())

    def test_unreadable_files_are_not_exempt(self):
        self.assertFalse(coverage_gate.is_generated({"path": ["/", "no", "such", "file.rs"]}))
        self.assertFalse(coverage_gate.is_generated({"path": "/no/such/file.rs"}))
        self.assertFalse(coverage_gate.is_generated({}))


if __name__ == "__main__":
    unittest.main()
