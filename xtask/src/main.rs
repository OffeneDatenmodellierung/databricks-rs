//! `cargo xtask codegen` — generate `community-databricks-sdk` service modules from
//! `spec/ir.json`.
//!
//! `cargo xtask codegen --check` fails if the committed output is stale.

#![allow(clippy::too_many_lines)] // emitters are long, linear templates

mod docs;
mod emit_model;
mod emit_openapi;
mod emit_service;
mod ir;
mod model;
mod names;

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use ir::{Ir, Service};

/// Identifiers generated modules import; a model type with one of these
/// names would shadow them.
const RESERVED: &[&str] = &["ApiClient", "Call", "Method", "Paged"];

/// Packages enabled by default.
const DEFAULT_FEATURES: &[&str] = &["catalog", "compute", "jobs", "provisioning"];

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if let Some("codegen") = args.first().map(String::as_str) {
        let check = args.iter().any(|a| a == "--check");
        match codegen(&root(), check) {
            Ok(()) => ExitCode::SUCCESS,
            Err(e) => {
                eprintln!("codegen: {e}");
                ExitCode::FAILURE
            }
        }
    } else {
        eprintln!("usage: cargo xtask codegen [--check]");
        ExitCode::FAILURE
    }
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("workspace root")
        .to_path_buf()
}

fn codegen(root: &Path, check: bool) -> Result<(), String> {
    let mut ir: Ir = serde_json::from_slice(
        &std::fs::read(root.join("spec/ir.json")).map_err(|e| format!("spec/ir.json: {e}"))?,
    )
    .map_err(|e| format!("spec/ir.json: {e}"))?;
    let patches: ir::Patches = serde_json::from_slice(
        &std::fs::read(root.join("codegen/ir_patches.json"))
            .map_err(|e| format!("codegen/ir_patches.json: {e}"))?,
    )
    .map_err(|e| format!("codegen/ir_patches.json: {e}"))?;
    ir.apply(&patches)?;
    let overrides: emit_service::Overrides = serde_json::from_slice(
        &std::fs::read(root.join("codegen/overrides.json"))
            .map_err(|e| format!("codegen/overrides.json: {e}"))?,
    )
    .map_err(|e| format!("codegen/overrides.json: {e}"))?;

    for (pkg, p) in &ir.packages {
        for t in &p.types {
            if RESERVED.contains(&t.name.as_str()) {
                return Err(format!("{pkg}.{} shadows a generated import", t.name));
            }
        }
    }

    let types = model::Types::new(&ir);
    let sdk = root.join("crates/community-databricks-sdk");
    let mut files: BTreeMap<PathBuf, String> = BTreeMap::new();
    let mut unsupported = Vec::new();
    let header = format!(
        "// Code generated by `cargo xtask codegen` from databricks-sdk-go {} (OpenAPI {}). DO NOT EDIT.\n",
        ir.source.go_sdk_version, ir.source.openapi_sha
    );

    // Services grouped by package; children by parent name.
    let mut by_pkg: BTreeMap<&str, Vec<&Service>> = BTreeMap::new();
    for s in &ir.services {
        by_pkg.entry(s.package.as_str()).or_default().push(s);
    }
    let deps = package_deps(&ir);
    let mut versions: BTreeMap<String, String> = BTreeMap::new();
    for (pkg, p) in &ir.packages {
        let dir = root.join("crates").join(model::crate_name(pkg));
        let has_ext = dir.join("src/ext.rs").exists();
        let mut out = String::new();
        out.push_str(&header);
        let _ = writeln!(
            out,
            "\n//! Databricks `{pkg}` API: models and services.\n//!\n//! Generated from databricks-sdk-go {}; use it through the\n//! [`community-databricks-sdk`](https://docs.rs/community-databricks-sdk) clients\n//! (`community_databricks_sdk::service::{pkg}`).\n\n#![allow(\n    clippy::all,\n    clippy::pedantic,\n    rustdoc::broken_intra_doc_links,\n    rustdoc::invalid_html_tags,\n    rustdoc::bare_urls,\n    unused_imports\n)]\n\nuse community_databricks_core::http::{{Call, Method, path_param}};\nuse community_databricks_core::paging::{{self, Paged}};\nuse community_databricks_core::{{ApiClient, query, wait}};\n",
            ir.source.go_sdk_version
        );
        if has_ext {
            // Hand-written helpers: methods on generated types, and any
            // public types or functions they add.
            out.push_str("\nmod ext;\n#[allow(unused_imports)]\npub use ext::*;\n");
        }
        out.push_str(&emit_model::emit(&types, p));
        for s in by_pkg.get(pkg.as_str()).into_iter().flatten() {
            let children: Vec<&Service> = ir
                .services
                .iter()
                .filter(|c| c.parent == s.name && c.package == s.package && c.client == s.client)
                .collect();
            out.push_str(&emit_service::emit(
                &types,
                s,
                &children,
                &overrides,
                &mut unsupported,
            ));
        }
        let services: Vec<&Service> = by_pkg
            .get(pkg.as_str())
            .into_iter()
            .flatten()
            .copied()
            .collect();
        out.push_str(&emit_service::emit_operation_states(&types, pkg, &services));
        files.insert(dir.join("src/lib.rs"), out);
        files.insert(
            dir.join("Cargo.toml"),
            package_manifest(pkg, &deps[pkg.as_str()], &crate_version(&dir)),
        );
        versions.insert(model::crate_name(pkg), crate_version(&dir));
    }

    // Umbrella: service re-exports, accessors, features and optional deps.
    let mut m = header.clone();
    m.push_str("\n//! Service packages, each a separate `community-databricks-sdk-<package>` crate\n//! enabled by the feature of the same name.\n\n");
    for pkg in ir.packages.keys() {
        let _ = writeln!(
            m,
            "#[cfg(feature = {pkg:?})]\n#[doc(inline)]\npub use {} as {pkg};",
            model::crate_ident(pkg)
        );
    }
    files.insert(sdk.join("src/service/mod.rs"), m);
    files.insert(sdk.join("src/accessors.rs"), accessors(&ir, &header));
    let cargo_path = sdk.join("Cargo.toml");
    let cargo = std::fs::read_to_string(&cargo_path).map_err(|e| e.to_string())?;
    files.insert(cargo_path, umbrella_manifest(&ir, &cargo)?);
    let root_manifest = root.join("Cargo.toml");
    let root_toml = std::fs::read_to_string(&root_manifest).map_err(|e| e.to_string())?;
    files.insert(root_manifest, workspace_manifest(&root_toml, &versions)?);

    // OpenAPI documents.
    let specs = emit_openapi::emit(&ir, &types);
    for (name, doc) in [("account", &specs.account), ("workspace", &specs.workspace)] {
        let mut text = serde_json::to_string_pretty(doc).map_err(|e| e.to_string())?;
        text.push('\n');
        files.insert(root.join(format!("spec/openapi/{name}.json")), text);
    }

    // Report.
    let mut report = String::from(
        "# Generated surface\n\nProduced by `cargo xtask codegen` from `spec/ir.json`. DO NOT EDIT.\n\n",
    );
    let _ = writeln!(
        report,
        "Source: databricks-sdk-go {} (OpenAPI `{}`).\n",
        ir.source.go_sdk_version, ir.source.openapi_sha
    );
    let nmeth: usize = ir
        .services
        .iter()
        .map(|s| s.methods.as_deref().unwrap_or_default().len())
        .sum();
    let ntypes: usize = ir.packages.values().map(|p| p.types.len()).sum();
    let _ = writeln!(
        report,
        "- {} packages, {} services, {} operations ({} generated), {} types.\n",
        ir.packages.len(),
        ir.services.len(),
        nmeth,
        nmeth - unsupported.len(),
        ntypes
    );
    report.push_str("## Not generated (binary or streaming payloads)\n\n");
    for u in &unsupported {
        let _ = writeln!(report, "- `{u}`");
    }
    report.push_str(
        "\n## OpenAPI path collisions (moved to `x-databricks-shared-path-operations`)\n\n",
    );
    for d in &specs.duplicates {
        let _ = writeln!(report, "- {d}");
    }
    report.push_str("\n## Skipped services\n\n");
    for s in &ir.skipped {
        let _ = writeln!(report, "- {s}");
    }
    report.push_str("\n## Hand-written overrides\n\n");
    for (k, v) in &overrides {
        let _ = writeln!(
            report,
            "- `{k}` is generated as `{v}`; see `src/ext.rs` in the package crate."
        );
    }
    files.insert(root.join("spec/GENERATED.md"), report);

    // rustfmt the Rust files in memory, then write or compare.
    let mut stale = Vec::new();
    for (path, content) in &files {
        let content = if path.extension().is_some_and(|e| e == "rs") {
            rustfmt(content)?
        } else {
            content.clone()
        };
        let current = std::fs::read_to_string(path).unwrap_or_default();
        if current == content {
            continue;
        }
        if check {
            stale.push(path.display().to_string());
        } else {
            std::fs::create_dir_all(path.parent().expect("parent")).map_err(|e| e.to_string())?;
            std::fs::write(path, content).map_err(|e| format!("{}: {e}", path.display()))?;
        }
    }
    // Remove crates for packages that no longer exist.
    let keep: BTreeSet<String> = ir.packages.keys().map(|p| model::crate_name(p)).collect();
    if let Ok(entries) = std::fs::read_dir(root.join("crates")) {
        for e in entries.flatten() {
            let name = e.file_name().to_string_lossy().to_string();
            let generated = std::fs::read_to_string(e.path().join("Cargo.toml"))
                .is_ok_and(|c| c.starts_with(GENERATED_MANIFEST));
            if generated && !keep.contains(&name) {
                if check {
                    stale.push(e.path().display().to_string());
                } else {
                    std::fs::remove_dir_all(e.path()).map_err(|e| e.to_string())?;
                }
            }
        }
    }
    if check && !stale.is_empty() {
        return Err(format!(
            "generated code is stale; run `cargo xtask codegen`:\n  {}",
            stale.join("\n  ")
        ));
    }
    eprintln!(
        "codegen: {} packages, {} services, {} operations, {} unsupported",
        ir.packages.len(),
        ir.services.len(),
        nmeth,
        unsupported.len()
    );
    Ok(())
}

fn accessors(ir: &Ir, header: &str) -> String {
    let mut out = String::from(header);
    out.push_str("\n//! Service accessors on the clients.\n\n#![allow(\n    clippy::doc_markdown,\n    clippy::too_many_lines,\n    rustdoc::broken_intra_doc_links,\n    rustdoc::invalid_html_tags,\n    rustdoc::bare_urls\n)]\n\nuse crate::{AccountClient, WorkspaceClient};\n\n");
    for (client, ty) in [
        ("workspace", "WorkspaceClient"),
        ("account", "AccountClient"),
    ] {
        let _ = writeln!(out, "impl {ty} {{");
        for s in ir
            .services
            .iter()
            .filter(|s| s.client == client && s.parent.is_empty())
        {
            let summary = docs::summary(&s.doc);
            let doc = if summary.is_empty() {
                format!("{} API.", s.name)
            } else {
                summary
            };
            out.push_str(&docs::render(&doc, "    "));
            let _ = writeln!(
                out,
                "    #[cfg(feature = {:?})]\n    #[must_use]\n    pub fn {}(&self) -> crate::service::{}::{} {{\n        crate::service::{}::{}::new(self.api_client().clone())\n    }}\n",
                s.package,
                names::method_ident(&s.accessor),
                s.package,
                emit_service::struct_name(s),
                s.package,
                emit_service::struct_name(s)
            );
        }
        out.push_str("}\n\n");
    }
    out
}

const GENERATED_MANIFEST: &str = "# Generated by `cargo xtask codegen`. DO NOT EDIT.";

/// Packages each package's types reference.
fn package_deps(ir: &Ir) -> BTreeMap<&str, BTreeSet<&str>> {
    let mut deps: BTreeMap<&str, BTreeSet<&str>> = BTreeMap::new();
    for (pkg, p) in &ir.packages {
        let set = deps.entry(pkg).or_default();
        for t in &p.types {
            let refs = t
                .fields
                .as_deref()
                .unwrap_or_default()
                .iter()
                .map(|f| &f.ty)
                .chain(t.alias.as_ref());
            for ty in refs {
                let mut r = Some(ty);
                while let Some(x) = r {
                    if x.kind == "ref" && x.pkg != *pkg && !x.pkg.is_empty() {
                        set.insert(x.pkg.as_str());
                    }
                    r = x.elem.as_deref();
                }
            }
        }
    }
    deps
}

/// A generated crate's current version, so codegen never undoes a
/// release-plz bump. New crates start at 0.1.0.
fn crate_version(dir: &Path) -> String {
    std::fs::read_to_string(dir.join("Cargo.toml"))
        .ok()
        .and_then(|toml| manifest_version(&toml))
        .unwrap_or_else(|| "0.1.0".to_owned())
}

/// `version = "…"` from a manifest's `[package]` table.
fn manifest_version(toml: &str) -> Option<String> {
    toml.split("[package]")
        .nth(1)?
        .lines()
        .take_while(|l| !l.starts_with('['))
        .find_map(|l| {
            let rest = l.trim().strip_prefix("version")?.trim_start();
            let v = rest.strip_prefix('=')?.trim().trim_matches('"');
            (!v.is_empty()).then(|| v.to_owned())
        })
}

/// Replace the text between `# BEGIN GENERATED {name}` and
/// `# END GENERATED {name}` in `src`.
fn replace_block(src: &str, file: &str, name: &str, body: &str) -> Result<String, String> {
    let begin = format!("# BEGIN GENERATED {name}");
    let end = format!("# END GENERATED {name}");
    let (Some(b), Some(e)) = (src.find(&begin), src.find(&end)) else {
        return Err(format!("{file} lacks `{begin}`/`{end}`"));
    };
    Ok(format!("{}{begin}\n{body}{}", &src[..b], &src[e..]))
}

/// The generated crates in the root `[workspace.dependencies]`, each with
/// its own version (release-plz bumps these alongside the crate).
fn workspace_manifest(root: &str, versions: &BTreeMap<String, String>) -> Result<String, String> {
    let mut body = String::new();
    for (name, v) in versions {
        let _ = writeln!(
            body,
            "{name} = {{ path = \"crates/{name}\", version = \"{v}\" }}"
        );
    }
    replace_block(root, "Cargo.toml", "WORKSPACE CRATES", &body)
}

fn package_manifest(pkg: &str, deps: &BTreeSet<&str>, version: &str) -> String {
    let mut out = format!(
        "{GENERATED_MANIFEST}\n\n[package]\nname = {:?}\ndescription = \"Databricks `{pkg}` API models and services (community-maintained, generated; use via community-databricks-sdk)\"\nreadme = \"../../README.md\"\nversion = \"{version}\"\nedition.workspace = true\nrust-version.workspace = true\nlicense.workspace = true\nrepository.workspace = true\nauthors.workspace = true\nkeywords.workspace = true\ncategories.workspace = true\n\n[dependencies]\ncommunity-databricks-core.workspace = true\nserde.workspace = true\nserde_json.workspace = true\n",
        model::crate_name(pkg)
    );
    for d in deps {
        let _ = writeln!(out, "{}.workspace = true", model::crate_name(d));
    }
    out.push_str("\n[lints]\nworkspace = true\n");
    out
}

/// Replace the generated feature and dependency blocks in the umbrella
/// Cargo.toml.
fn umbrella_manifest(ir: &Ir, cargo: &str) -> Result<String, String> {
    let file = "crates/community-databricks-sdk/Cargo.toml";
    let mut features = String::new();
    let defaults: Vec<String> = DEFAULT_FEATURES.iter().map(|f| format!("{f:?}")).collect();
    let _ = writeln!(features, "default = [{}]", defaults.join(", "));
    let all: Vec<String> = ir.packages.keys().map(|k| format!("{k:?}")).collect();
    let _ = writeln!(features, "full = [{}]", all.join(", "));
    let mut deps = String::new();
    for pkg in ir.packages.keys() {
        let _ = writeln!(features, "{pkg} = [\"dep:{}\"]", model::crate_name(pkg));
        let _ = writeln!(
            deps,
            "{} = {{ workspace = true, optional = true }}",
            model::crate_name(pkg)
        );
    }
    let cargo = replace_block(cargo, file, "FEATURES", &features)?;
    replace_block(&cargo, file, "DEPENDENCIES", &deps)
}

fn rustfmt(src: &str) -> Result<String, String> {
    use std::io::Write as _;
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()
        .map_err(|e| format!("rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .expect("stdin")
        .write_all(src.as_bytes())
        .map_err(|e| e.to_string())?;
    let out = child.wait_with_output().map_err(|e| e.to_string())?;
    if !out.status.success() {
        let dump = std::env::temp_dir().join("xtask-rustfmt-failed.rs");
        let _ = std::fs::write(&dump, src);
        return Err(format!(
            "rustfmt failed (input saved to {}):\n{}",
            dump.display(),
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    String::from_utf8(out.stdout).map_err(|e| e.to_string())
}

#[cfg(test)]
mod manifest_tests {
    use super::*;

    #[test]
    fn versions_are_read_from_the_package_table() {
        let toml =
            "[package]\nname = \"x\"\nversion = \"1.4.2\"\n\n[dependencies]\nversion = \"9\"\n";
        assert_eq!(manifest_version(toml).as_deref(), Some("1.4.2"));
        assert_eq!(
            manifest_version("[package]\nversion.workspace = true\n"),
            None
        );
        assert_eq!(manifest_version("[workspace]\n"), None);
        assert_eq!(crate_version(Path::new("/no/such/crate")), "0.1.0");
    }

    #[test]
    fn workspace_block_lists_each_crate_with_its_version() {
        let root = "[workspace.dependencies]\n# BEGIN GENERATED WORKSPACE CRATES\nold = 1\n# END GENERATED WORKSPACE CRATES\nserde = \"1\"\n";
        let versions = BTreeMap::from([
            ("community-databricks-sdk-a".to_owned(), "0.3.0".to_owned()),
            ("community-databricks-sdk-b".to_owned(), "1.0.0".to_owned()),
        ]);
        let out = workspace_manifest(root, &versions).unwrap();
        assert!(out.contains("community-databricks-sdk-a = { path = \"crates/community-databricks-sdk-a\", version = \"0.3.0\" }"));
        assert!(out.contains("version = \"1.0.0\""));
        assert!(!out.contains("old = 1"));
        assert!(out.ends_with("# END GENERATED WORKSPACE CRATES\nserde = \"1\"\n"));
        assert!(
            workspace_manifest("[workspace]\n", &versions)
                .unwrap_err()
                .contains("lacks")
        );
    }

    #[test]
    fn package_manifests_use_workspace_dependencies() {
        let m = package_manifest("jobs", &BTreeSet::from(["compute"]), "0.4.0");
        assert!(m.contains("name = \"community-databricks-sdk-jobs\""));
        assert!(m.contains("version = \"0.4.0\""));
        assert!(m.contains("community-databricks-sdk-compute.workspace = true"));
        assert!(m.starts_with(GENERATED_MANIFEST));
    }
}
